# ---------- Git access (read-only) ----------

def git(repo, *args):
    r = subprocess.run(["git", "-C", repo, *args], capture_output=True)
    if r.returncode != 0:
        fail(f"git {' '.join(args)} failed: {r.stderr.decode('utf-8', 'replace').strip()}")
    return r.stdout


class Source:
    """The files of one commit, read through `git show`."""

    def __init__(self, repo, commit):
        self.repo = repo
        self.commit = git(repo, "rev-parse", "--verify", commit + "^{commit}").decode().strip()
        self.paths = set(git(repo, "ls-tree", "-r", "--name-only", self.commit).decode("utf-8").splitlines())
        self._cache = {}

    def exists(self, path):
        path = path.rstrip("/")
        return path in self.paths or any(p.startswith(path + "/") for p in self.paths)

    def read(self, path):
        if path not in self._cache:
            if path not in self.paths:
                fail(f"missing reference: {path} does not exist at {self.commit[:12]}")
            self._cache[path] = git(self.repo, "show", f"{self.commit}:{path}").decode("utf-8").replace("\r\n", "\n")
        return self._cache[path]


class DictSource:
    """In-memory sources for tests: {path: text}."""

    def __init__(self, files, commit="0" * 40):
        self.commit, self.files, self.paths = commit, dict(files), set(files)

    def exists(self, path):
        path = path.rstrip("/")
        return path in self.paths or any(p.startswith(path + "/") for p in self.paths)

    def read(self, path):
        if path not in self.files:
            fail(f"missing reference: {path} does not exist at {self.commit[:12]}")
        return self.files[path].replace("\r\n", "\n")


# ---------- Markdown helpers ----------

FM_RE = re.compile(r"---\n(.*?)\n---\n", re.S)
HEADING_RE = re.compile(r"^(#{1,6})[ \t]+(.+?)[ \t]*#*[ \t]*$")
FENCE_RE = re.compile(r"^\s*(```|~~~)")
LINK_RE = re.compile(r"(!?)\[([^\]\n]+)\]\(([^)\s]+)\)")
EXTERNAL_RE = re.compile(r"^[a-z][a-z0-9+.-]*:", re.I)


def split_frontmatter(text):
    m = FM_RE.match(text)
    return (m.group(1), text[m.end():].lstrip("\n")) if m else ("", text)


def anchor(heading):
    """GitHub-style anchor of a heading."""
    s = re.sub(r"[^\w\- ]", "", heading.strip().lower())
    return s.replace(" ", "-")


def headings(text):
    """[(line_index, level, text)] outside fenced code."""
    out, fenced = [], False
    for i, line in enumerate(text.split("\n")):
        if FENCE_RE.match(line):
            fenced = not fenced
            continue
        if not fenced:
            m = HEADING_RE.match(line)
            if m:
                out.append((i, len(m.group(1)), m.group(2)))
    return out


def section(text, heading, where):
    """The text of one section, heading line included, and its level. Missing or ambiguous headings fail."""
    hs = headings(text)
    hits = [h for h in hs if h[2] == heading]
    if not hits:
        fail(f"missing heading {heading!r} in {where} (headings there: {[h[2] for h in hs]})")
    if len(hits) > 1:
        fail(f"ambiguous heading {heading!r} in {where} ({len(hits)} matches)")
    start, level, _ = hits[0]
    lines = text.split("\n")
    end = next((i for i, lv, _ in hs if i > start and lv <= level), len(lines))
    return "\n".join(lines[start:end]).strip("\n"), level


def blocks(text):
    """Blank-line separated blocks, with fenced code kept whole."""
    out, cur, fenced = [], [], False
    for line in text.split("\n"):
        if FENCE_RE.match(line):
            fenced = not fenced
        if not fenced and line.strip() == "" and cur:
            out.append("\n".join(cur))
            cur = []
        elif not fenced and HEADING_RE.match(line):
            if cur:
                out.append("\n".join(cur))
            out.append(line)
            cur = []
        elif fenced or line.strip() != "":
            cur.append(line)
    if cur:
        out.append("\n".join(cur))
    return out


def shift_headings(text, delta):
    if delta == 0:
        return text
    out, fenced = [], False
    for line in text.split("\n"):
        if FENCE_RE.match(line):
            fenced = not fenced
        elif not fenced:
            m = HEADING_RE.match(line)
            if m:
                line = "#" * max(1, min(6, len(m.group(1)) + delta)) + " " + m.group(2)
        out.append(line)
    return "\n".join(out)


def strip_external_links(text):
    return re.sub(r"\[([^\]]+)\]\((?:https?|mailto):[^)]*\)", "", text)


# ---------- normative sentences ----------

NORMATIVE_RE = re.compile(r"\b[Mm][Uu][Ss][Tt]\b|\bSHALL\b|\bREQUIRED\b|\b[Nn]ever\b|\b[Dd]o not\b|\bnot allowed\b|\bNot approved\b|"
                          r"\ballows exactly\b|\bonly when\b")


def norm(s):
    """Whitespace, emphasis, list markers and quote characters are not content."""
    s = s.replace("**", "").replace("`", "")
    s = re.sub(r"(^|\n)[ \t]*(?:\d+\.|-|\|)[ \t]+", r"\1", s)
    s = s.replace("|", " ")
    return re.sub(r"\s+", " ", s).strip()


def sentences(text):
    """Sentences of prose and list items; each table row is one sentence."""
    out = []
    for b in blocks(text):
        if b.lstrip().startswith("|"):
            out += [r for r in b.split("\n") if not re.fullmatch(r"\|[-:| ]+\|", r.strip())]
            continue
        if b.lstrip().startswith(("```", "~~~")) or HEADING_RE.match(b.split("\n")[0]):
            if HEADING_RE.match(b.split("\n")[0]):
                b = "\n".join(b.split("\n")[1:])
            else:
                continue
        flat = re.sub(r"\s*\n\s*(?=(?:\d+\.|-)\s)", "\n", b)
        for item in flat.split("\n"):
            item = re.sub(r"\s+", " ", item)
            out += [p.strip() for p in re.split(r"(?<=[.!?])\s+(?=[A-Z`\"(*@\d])", item) if p.strip()]
    return [s for s in out if s and not s.startswith("<!--")]


def normative(text):
    return [s for s in sentences(text) if NORMATIVE_RE.search(s)]


# ---------- conflicts ----------

RULE_HEADING_RE = re.compile(r"^(R\d+)\.\s")
ITEM_RE = re.compile(r"^(\d+)\.\s+(.*)$")
EXPLICIT_ID_RE = re.compile(r"^\s*(?:[-*]|\d+\.)?\s*\*\*([A-Z]{1,4}-?\d+(?:\.\d+)?)\*\*[:.]?\s+(.*)$")
MUST_RE = re.compile(r"\b(MUST NOT|MUST)\s+(.+?)(?=[.;:]\s|[.;:]?$)")
NEVER_RE = re.compile(r"(?:^|[.;]\s+)Never\s+(.+?)(?=[.;:]\s|[.;:]?$)")
STOP = {"you", "the", "a", "an", "your", "any", "be", "to"}


def rule_ids(text):
    """Rule ids defined in a text: `R<n>.<item>` from an `R<n>.` heading and its numbered items, and explicit
    `**ID-NNN**` list leads. Returns {id: normalized text}."""
    out, current = {}, None
    for line in text.split("\n"):
        m = HEADING_RE.match(line)
        if m:
            r = RULE_HEADING_RE.match(m.group(2))
            current = r.group(1) if r else None
            continue
        if current:
            it = ITEM_RE.match(line.strip())
            if it and not line.startswith((" ", "\t")):
                out[f"{current}.{it.group(1)}"] = norm(it.group(2))
        e = EXPLICIT_ID_RE.match(line)
        if e:
            out[e.group(1)] = norm(e.group(2))
    return out


def obligation_key(clause):
    words = [w for w in re.sub(r"[^\w\s-]", " ", clause.lower()).split() if w not in STOP]
    return " ".join(words[:6])


def obligations(text):
    """[(polarity, key, sentence)]: `MUST X` -> (+, X); `MUST NOT X` and sentence-initial `Never X` -> (-, X)."""
    out = []
    for s in sentences(text):
        for m in MUST_RE.finditer(s.replace("`", "")):
            out.append(("-" if m.group(1) == "MUST NOT" else "+", obligation_key(m.group(2)), s))
        for m in NEVER_RE.finditer(s.replace("`", "")):
            out.append(("-", obligation_key(m.group(1)), s))
    return [o for o in out if o[1]]


def find_conflicts(units):
    """Lexical conflict lint, not a proof that every policy conflict is resolved.

    units: [(label, text)]. Two kinds:
    1. the same rule id defined with different texts in two units;
    2. one unit says `MUST X` and another (or the same) says `MUST NOT X` / `Never X`, where X is compared on its
       first six words after lower-casing and dropping punctuation and filler words.
    A sentence the patterns do not recognize is not checked. An empty result does not mean the texts agree."""
    found, ids, polar = [], {}, {}
    for label, text in units:
        for rid, t in rule_ids(text).items():
            if rid in ids and ids[rid][1] != t:
                found.append(f"rule id {rid} has two texts: {ids[rid][0]} vs {label}")
            ids.setdefault(rid, (label, t))
        for pol, key, s in obligations(text):
            polar.setdefault(key, {}).setdefault(pol, []).append((label, s))
    for key in sorted(polar):
        if "+" in polar[key] and "-" in polar[key]:
            a, b = polar[key]["+"][0], polar[key]["-"][0]
            found.append(f"contradictory obligation on '{key}': {a[0]} says {a[1]!r}; {b[0]} says {b[1]!r}")
    return found


# ---------- link rewriting (unavailable channels) ----------

def rewrite_links(text, src_path, src, included, on_request, log):
    """Relative links into Company OS cannot be opened from a Task Workspace. Each one becomes plain text:
    `label (in this file)` when its target is delivered in this file, else `label (on request)`; the target path is
    listed in the Knowledge index and in package.json (link_rewrites). A missing target or anchor stops the run."""
    out, fenced = [], False

    def repl(m):
        bang, label, target = m.groups()
        if EXTERNAL_RE.match(target):
            log.append({"source": src_path, "from": target, "kind": "external-kept"})
            return m.group(0)
        path_part, _, anc = target.partition("#")
        resolved = posixpath.normpath(posixpath.join(posixpath.dirname(src_path), path_part)) if path_part else src_path
        if resolved.startswith(".."):
            fail(f"missing reference: link in {src_path} points outside Company OS: {target}")
        if not src.exists(resolved):
            fail(f"missing reference: link in {src_path} -> {resolved} does not exist at {src.commit[:12]}")
        if anc and resolved.endswith(".md") and resolved in src.paths:
            if anc not in {anchor(h[2]) for h in headings(split_frontmatter(src.read(resolved))[1])}:
                fail(f"missing reference: anchor #{anc} not found in {resolved} (link in {src_path})")
        if (resolved, anc) in included or (resolved, "*") in included:
            new, kind = f"{label} (in this file)", "included"
        else:
            new, kind = f"{label} (on request)", "on-request"
            on_request.setdefault(resolved, set()).add(src_path)
        log.append({"source": src_path, "from": target, "to": new, "kind": kind})
        return new

    for line in text.split("\n"):
        if FENCE_RE.match(line):
            fenced = not fenced
            out.append(line)
            continue
        out.append(line if fenced else LINK_RE.sub(repl, line))
    return "\n".join(out)


# ---------- permission rules (for the command-form guard and skill procedures) ----------

def bash_match(rule, cmd):
    """Claude Code `Bash(pattern)` rule against a command: `*` matches any run of characters."""
    m = re.fullmatch(r"Bash\((.*)\)", rule)
    if not m:
        return False
    return re.fullmatch(".*".join(re.escape(p) for p in m.group(1).split("*")), cmd, re.S) is not None


def role_rules(agents, role, prefix="SOU"):
    """(allow, deny) Bash rules of a claude_local role exactly as build-package.py builds them."""
    spec = agents["agents"][role]
    prof = agents["profiles"][spec["profile"]]
    if prof["adapter"] != "claude_local":
        return [], []
    sub = lambda xs: [x.replace("{PREFIX}", prefix) for x in xs]  # noqa: E731
    return sub(prof.get("allowedTools", []) + spec.get("extraAllowedTools", [])), sub(prof.get("disallowedTools", []))


def permitted(cmd, allow, deny):
    """The allow rule that permits `cmd`, or None. A matching deny rule wins."""
    if any(bash_match(d, cmd) for d in deny):
        return None
    return next((a for a in allow if bash_match(a, cmd)), None)


