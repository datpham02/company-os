# ---------- token estimate (no tokenizer is called) ----------

PIECE_RE = re.compile(r"[A-Za-z]+|\d+|[^\sA-Za-z\d]")


def tokens_estimate(text):
    """ESTIMATED tokens. Two heuristics, no tokenizer: chars/3.6 (English Markdown rule of thumb) and a piece count
    (each word ceil(len/6), each digit run ceil(len/3), each symbol 1)."""
    pieces = 0
    for p in PIECE_RE.findall(text):
        pieces += max(1, math.ceil(len(p) / (6 if p[0].isalpha() else 3))) if p[0].isalnum() else 1
    a = round(len(text) / 3.6)
    return {"chars_div_3_6": a, "piece_heuristic": pieces, "low": min(a, pieces), "high": max(a, pieces)}


# ---------- unit extraction ----------

def section_blocks(text, path, heading, splits):
    """Blocks of one section. `splits` {(path, heading): [phrase, ...]} cuts a block before each phrase, so that one
    long paragraph can be shared between units (for example core prose and exact command forms). Each phrase must
    occur exactly once in the section."""
    bl = blocks(text)
    for phrase in (splits or {}).get((path, heading), []):
        hits = [i for i, b in enumerate(bl) if b.find(phrase) > 0]
        if len(hits) != 1 or sum(b.count(phrase) for b in bl) != 1:
            fail(f"block split {phrase!r} must occur exactly once inside a block of {path} § {heading}")
        i = hits[0]
        k = bl[i].find(phrase)
        bl[i:i + 1] = [bl[i][:k].rstrip(), bl[i][k:]]
    return bl


def extract_unit(src, u, splits=None):
    """Raw text of one manifest unit (headings, blocks or lines of one source file), plus details for coverage."""
    path = u["source"]
    if not src.exists(path):
        fail(f"missing reference: unit {u['id']}: {path} does not exist at {src.commit[:12]}")
    _, body = split_frontmatter(src.read(path))
    parts, covered = [], []
    if "lines_containing" in u:
        lines = body.split("\n")
        for needle in u["lines_containing"]:
            hits = [ln for ln in lines if needle in ln]
            if len(hits) != 1:
                fail(f"unit {u['id']}: {len(hits)} lines in {path} contain {needle!r} (need exactly 1)")
            parts.append(hits[0].strip())
        return "\n".join(parts), 3, covered
    level = None
    for h in u["headings"]:
        if h == "(preamble)":
            first = next((i for i, lv, _ in headings(body) if lv == 2), len(body.split("\n")))
            text, lv = "\n".join(body.split("\n")[:first]).strip("\n"), 1
        else:
            text, lv = section(body, h, path)
        level = lv if level is None else min(level, lv)
        bl = section_blocks(text, path, h, splits)
        if u.get("blocks_starting_with"):
            head = bl[0] if HEADING_RE.match(bl[0]) else None
            chosen = []
            for prefix in u["blocks_starting_with"]:
                hits = [i for i, b in enumerate(bl) if b.startswith(prefix)]
                if len(hits) != 1:
                    fail(f"unit {u['id']}: {len(hits)} blocks of {path} § {h} start with {prefix!r} (need exactly 1)")
                chosen.append(hits[0])
            covered += [(path, h, i) for i in chosen]
            body_part = "\n\n".join(bl[i] for i in sorted(chosen))
            title = u.get("title") or (head and HEADING_RE.match(head).group(2))
            parts.append((f"{'#' * lv} {title}\n\n" if title else "") + body_part)
        else:
            covered += [(path, h, i) for i in range(len(bl))]
            parts.append(text)
    return "\n\n".join(parts), level, covered


def check_role_coverage(src, role_file, covered, role, splits=None):
    """Every block of every `##` section (and the preamble) of the role file is claimed by exactly one unit."""
    _, body = split_frontmatter(src.read(role_file))
    want = set()
    first = next((i for i, lv, _ in headings(body) if lv == 2), None)
    if first:
        want |= {(role_file, "(preamble)", i) for i in range(len(blocks("\n".join(body.split("\n")[:first]))))}
    for _, lv, h in headings(body):
        if lv == 2:
            bl = section_blocks(section(body, h, role_file)[0], role_file, h, splits)
            want |= {(role_file, h, i) for i in range(len(bl)) if not HEADING_RE.match(bl[i])}
    got = [c for c in covered if c[0] == role_file]
    dup = sorted({c for c in got if got.count(c) > 1})
    if dup:
        fail(f"{role}: role-file blocks claimed twice: {dup}")
    missing = sorted(want - set(got), key=lambda c: (c[1], c[2]))
    if missing:
        fail(f"{role}: source coverage: role-file blocks claimed by no unit: {missing}")
    return sorted(want)


# ---------- package build ----------

def marker(u, commit, digest, role, dept):
    """One-line provenance comment that opens every generated section. Several headings of one source are written
    `#first..last`; the full heading list and per-heading hashes are in package.json."""
    hs = [anchor(h) if h != "(preamble)" else "preamble" for h in u.get("headings", [])]
    anchors = (hs[0] if len(hs) == 1 else f"{hs[0]}..{hs[-1]}") if hs else "lines"
    part = "(part)" if u.get("blocks_starting_with") else ""
    return (f"<!-- kd:unit {u['id']} src={u['source']}#{anchors}{part} @{commit[:12]} sha256={digest[:16]} "
            f"status={u['status']} role={role} dept={dept} auth=\"{u['authority']}\" delivery={u['delivery']} -->")


def validate_manifest(manifest):
    if manifest.get("schema") != MANIFEST_SCHEMA:
        fail(f"unknown manifest schema {manifest.get('schema')!r} (expected {MANIFEST_SCHEMA})")
    for role, spec in manifest["roles"].items():
        ids = [u["id"] for u in spec["units"]]
        if len(ids) != len(set(ids)):
            fail(f"{role}: duplicate unit ids")
        keys = [(u["source"], h, tuple(u.get("blocks_starting_with", []))) for u in spec["units"] for h in u.get("headings", [])]
        if len(keys) != len(set(keys)):
            fail(f"{role}: a section is listed twice")
        for u in spec["units"]:
            for k in ("id", "source", "status", "authority", "delivery"):
                if not u.get(k):
                    fail(f"{role}: unit {u.get('id')} has no {k!r}")
            if u["status"] not in STATUSES:
                fail(f"{role}: unit {u['id']} status {u['status']!r} is not one of {sorted(STATUSES)}")
            if u["delivery"] not in DELIVERIES:
                fail(f"{role}: unit {u['id']} delivery {u['delivery']!r} is not one of {list(DELIVERIES)}")
            if u["status"] in ("experimental", "superseded") and u["delivery"] in DELIVERED:
                fail(f"{role}: unit {u['id']} is {u['status']} and may not be delivered as {u['delivery']} "
                     "(never emitted as an approved production rule)")


LABEL_RE = re.compile(r"`(PROPOSED|PLANNED|DEPRECATED)`")


def build_role(role, manifest, src, agents, manifest_sha, manifest_origin, generator_sha):
    spec = manifest["roles"][role]
    dept = spec["department"]
    role_file = spec["role_file"]
    fm, _ = split_frontmatter(src.read(role_file))
    slug = re.search(r"^slug:\s*(\S+)", fm, re.M)
    if (slug.group(1) if slug else posixpath.basename(posixpath.dirname(role_file))) != role:
        fail(f"{role_file}: its slug does not match manifest role {role!r}")
    if agents["agents"].get(role, {}).get("department") != dept:
        fail(f"{role}: department {dept!r} differs from agents.json")

    splits = {(s["source"], s["heading"]): s["before"] for s in spec.get("block_splits", [])}
    units, covered = [], []
    for u in spec["units"]:
        raw, level, cov = extract_unit(src, u, splits)
        covered += cov
        first = next((b for b in blocks(raw) if not HEADING_RE.match(b)), "").split("\n")[0]
        if u["status"] == "approved" and LABEL_RE.search(first):
            fail(f"{role}: unit {u['id']} is declared approved but its source says {LABEL_RE.search(first).group(0)}")
        units.append({**u, "raw": raw, "level": level})
    coverage = check_role_coverage(src, role_file, covered, role, splits)

    delivered = [u for u in units if u["delivery"] in DELIVERED]
    included = {}
    for u in delivered:
        for h in u.get("headings", []):
            included[(u["source"], anchor(h) if h != "(preamble)" else "")] = u["id"]
    on_request, link_log = {}, []
    for u in units:
        if u["delivery"] == "on_request":
            for h in u.get("headings", []):
                on_request.setdefault(f"{u['source']} § {h}", set()).add(f"manifest unit {u['id']} (on_request fallback)")
        elif u["delivery"] == "on_demand_verified":
            for h in u.get("headings", []):
                on_request.setdefault(f"{u['source']} § {h}", set()).add(
                    f"manifest unit {u['id']} (on_demand_verified; listed, not pasted)")
    for u in units:
        txt = u["raw"]
        if u["source"] == role_file:
            txt = shift_headings(txt, 0)
        elif u.get("level"):
            txt = shift_headings(txt, 3 - u["level"])
        if u["delivery"] in DELIVERED:
            u["out"] = rewrite_links(txt, u["source"], src, included, on_request, link_log)
        else:
            u["out"] = txt
    for p in spec.get("on_demand_documents", []):
        if not src.exists(p):
            fail(f"missing reference: on-demand document {p} does not exist at {src.commit[:12]}")
        on_request.setdefault(p, set()).add("manifest")

    rules = {k: agents["rules"][k] for k in agents["profiles"][agents["agents"][role]["profile"]].get("rules", [])}
    system_text = "\n\n".join(rules.values())
    delivered_text = "\n\n".join(u["out"] for u in delivered) + "\n\n" + system_text
    delivered_norm = norm(delivered_text)

    # Mandatory content and exact command forms must stay in the verified channels.
    # Coverage entries are a lexical lint (substring), not a semantic check, and they must not be used to drop a duty
    # the sentence detector missed: a non-verified unit still has to carry every block the manifest selected.
    allow, deny = role_rules(agents, role)
    guard, problems = [], []
    cover = spec.get("coverage", [])
    used_cover = set()
    for u in units:
        if u["delivery"] in DELIVERED:
            continue
        for s in normative(u["raw"]):
            if norm(s) in delivered_norm:
                guard.append({"unit": u["id"], "sentence": s, "result": "verbatim in delivered text"})
                continue
            hit = next((i for i, c in enumerate(cover) if c["unit"] == u["id"] and c["match"] in s), None)
            if hit is None:
                problems.append(f"unit {u['id']} ({u['delivery']}): {s!r} is not in the delivered text and has no "
                                "coverage entry")
                continue
            c = cover[hit]
            used_cover.add(hit)
            if "not_applicable" in c:
                guard.append({"unit": u["id"], "sentence": s, "result": f"not applicable: {c['not_applicable']}"})
                continue
            missing = [p for p in c["covered_by"] if norm(p) not in delivered_norm]
            if missing:
                problems.append(f"unit {u['id']}: coverage for {s!r} names phrases not in the delivered text: {missing}")
                continue
            guard.append({"unit": u["id"], "sentence": s,
                          "result": "lexical lint, not semantic equivalence; phrases present: " + " | ".join(c["covered_by"])})
        for span in CMD_SPAN_RE.findall(u["raw"]):
            if permitted(span, allow, deny) and norm(span) not in delivered_norm:
                problems.append(f"exact allowed command form `{span}` appears only in unit {u['id']} ({u['delivery']})")
    if problems:
        fail(f"{role}: mandatory content would leave the verified channels:\n  " + "\n  ".join(problems))
    stale = [cover[i] for i in range(len(cover)) if i not in used_cover]
    if stale:
        fail(f"{role}: coverage entries that match no sentence (stale manifest): {stale}")

    conflicts = find_conflicts([(u["id"], u["out"]) for u in delivered] + [("system-prompt", system_text)])
    if conflicts:
        fail(f"{role}: conflicting mandatory policies:\n  " + "\n  ".join(conflicts))

    # Duplicate content (reported; the role file and the company rules each stay whole).
    seen, duplicates = {}, []
    for label, text in [("system-prompt", system_text)] + [(u["id"], u["out"]) for u in delivered]:
        for s in sentences(text):
            n = norm(s)
            if len(n) < 40:
                continue
            if n in seen and seen[n] != label:
                duplicates.append({"sentence": s, "first": seen[n], "again": label, "bytes": len(s.encode("utf-8"))})
            seen.setdefault(n, label)

    # Assemble.
    core, cmd = [], []
    for u in units:
        if u["delivery"] not in DELIVERED:
            continue
        u["source_sha256"] = sha256(u["raw"])
        u["emitted_sha256"] = sha256(u["out"])
        piece = marker(u, src.commit, u["source_sha256"], role, dept) + "\n" + u["out"].strip("\n")
        if u["delivery"] == "always_loaded" and u["source"] != role_file and not any(
                x["source"] != role_file and x["delivery"] == "always_loaded" for x in units[:units.index(u)]):
            core.append(manifest["company_rules_heading"])
        (core if u["delivery"] == "always_loaded" else cmd).append(piece)
    intro = manifest["package_intro"].format(role=role)
    idx = ["## Knowledge index", ""]
    if spec.get("project_documents"):
        idx += ["### On demand, verified channel", "",
                "Project repository paths. Stage 1 could open project documents from the Task Workspace. "
                "That does not make Company OS paths readable, and it is not a claim that every file exists.", ""]
        idx += [f"- `{p}`" for p in spec["project_documents"]]
        idx.append("")
    idx += ["### On request (fallback, not verified delivery)", "", manifest["on_request_note"], ""]
    # A section is listed only when its whole file is not listed already.
    idx += [f"- {k}" for k in sorted(on_request) if " § " not in k or k.split(" § ")[0] not in on_request]
    idx += ["", "### Skill assigned", "",
            "A skill assignment is not verified delivery until a run shows the skill and its supporting file were opened."]
    for sk in spec.get("skills", []):
        idx += ["", f"Skill `{sk['name']}` (`{STATUSES[sk['status']]}`): {sk['note']} "
                "This is the Knowledge Delivery pilot skill, not the deferred animation skill package (K5)."]
    core_text = "\n\n".join([intro] + core + ["\n".join(idx)])
    cmd_text = "\n\n".join([manifest["command_reference_intro"]] + cmd) if cmd else ""
    body = core_text + ("\n\n" + cmd_text if cmd_text else "") + "\n"
    if LINK_RE.search(strip_external_links(body)):
        fail(f"{role}: unavailable channel: a relative link survived rewriting: {LINK_RE.search(strip_external_links(body)).group(0)}")
    pkg_sha = sha256(body)
    header = (f"<!-- GENERATED by {GENERATOR} v{GENERATOR_VERSION} for role {role}. Do not edit by hand. "
              f"source-commit={src.commit} package-sha256={pkg_sha} -->\n")
    doc = header + body
    # The command-reference block is everything from its heading to the end of the file; the core is the rest.
    cmd_bytes = len(("\n\n" + cmd_text + "\n").encode("utf-8")) if cmd_text else 0
    core_bytes = len(doc.encode("utf-8")) - cmd_bytes
    b = manifest["budget"]
    applies = b.get("applies_to")
    checked = applies is None or role in applies
    budget = {"core_bytes": core_bytes, "command_reference_bytes": cmd_bytes, "combined_bytes": core_bytes + cmd_bytes,
              "core_max_bytes": b["core_max_bytes"], "command_reference_max_bytes": b["command_reference_max_bytes"],
              "combined_max_bytes": b["combined_max_bytes"], "checked": checked,
              "applies_to": applies, "authority": b.get("authority")}
    unit_rows = [{"id": u["id"], "source": u["source"], "headings": u.get("headings"),
                  "blocks_starting_with": u.get("blocks_starting_with"), "lines_containing": u.get("lines_containing"),
                  "status": u["status"], "status_label": STATUSES[u["status"]], "authority": u["authority"],
                  "delivery": u["delivery"], "role": role, "department": dept, "source_commit": src.commit,
                  "source_sha256": sha256(u["raw"]), "emitted_sha256": sha256(u["out"]),
                  "emitted_bytes": len(u["out"].encode("utf-8")) if u["delivery"] in DELIVERED else 0,
                  "section_sha256": {h: sha256(section(split_frontmatter(src.read(u["source"]))[1], h, u["source"])[0])
                                     for h in u.get("headings", []) if h != "(preamble)"}}
                 for u in units]
    pkg = {
        "schema": "role-knowledge-package.v1",
        "generated_note": "Generated file. Do not edit by hand.",
        "role": role, "department": dept,
        "generator": {"path": GENERATOR, "version": GENERATOR_VERSION, "sha256": generator_sha},
        "manifest": {"path": MANIFEST, "sha256": manifest_sha, "origin": manifest_origin},
        "source_commit": src.commit,
        "package_sha256": pkg_sha,
        "checks": {
            "integrity": "header package-sha256 equals the body below the header",
            "reproducibility": "regenerate at source_commit with this generator and the manifest that produced the package; --check. Success does not mean the knowledge is current.",
            "freshness": "compare each unit section_sha256 to a target revision's file bytes. Unrelated files are ignored. source_commit equality is not required.",
        },
        "role_file": role_file,
        "units": unit_rows,
        "source_coverage": {"role_file_blocks": len(coverage),
                            "delivered_units_with_marker": [u["id"] for u in delivered]},
        "system_prompt_rules": {k: {"sha256": sha256(v), "chars": len(v)} for k, v in rules.items()},
        "mandatory_guard": guard,
        "coverage_method": LEXICAL_COVERAGE_NOTE,
        "conflict_lint": LEXICAL_COVERAGE_NOTE,
        "duplicates": duplicates,
        "duplicate_bytes": sum(d["bytes"] for d in duplicates),
        "conflicts": conflicts,
        "on_request": {k: sorted(v) for k, v in sorted(on_request.items())},
        "link_rewrites": link_log,
        "budget": budget,
        "tokens_estimated": {"method": "ESTIMATED, no tokenizer: chars/3.6 and a piece heuristic "
                                       "(word ceil(len/6), digit run ceil(len/3), symbol 1)",
                             "core": tokens_estimate(header + core_text),
                             "command_reference": tokens_estimate(cmd_text),
                             "combined": tokens_estimate(doc)},
        "memory_policy": spec.get("memory_policy"),
        "settings_file": spec.get("settings_file"),
        "skills": spec.get("skills", []),
    }
    over = [k for k, mx in (("core_bytes", "core_max_bytes"), ("command_reference_bytes", "command_reference_max_bytes"),
                            ("combined_bytes", "combined_max_bytes")) if budget[k] > budget[mx]]
    if over and checked:
        table = "\n".join(f"  {r['id']:28} {r['delivery']:17} {r['emitted_bytes']:6} B  {r['source']}" for r in unit_rows)
        fail(f"{role}: over budget ({', '.join(f'{k}={budget[k]} > {budget[k.replace('_bytes', '_max_bytes')]}' for k in over)}). "
             f"Nothing was dropped. Duplicate sentences found: {len(duplicates)} ({pkg['duplicate_bytes']} B). Units:\n{table}")
    return doc, pkg


# ---------- dependency registry (minimal line parser for the keys used here) ----------

def parse_registry(text):
    """{id: {"line": n, "integrationStatus": .., "verifiedVersion": .., "name": ..}} of dependencies/registry.yaml."""
    out, cur = {}, None
    for n, line in enumerate(text.split("\n"), 1):
        m = re.match(r"^  - id:\s*(\S+)", line)
        if m:
            cur = out.setdefault(m.group(1), {"line": n})
            continue
        m = re.match(r"^    (integrationStatus|verifiedVersion|name):\s*(.*)$", line) if cur is not None else None
        if m:
            raw = m.group(2).strip()
            if raw.startswith('"'):
                raw = raw[1:].split('"', 1)[0]
            else:
                raw = re.sub(r"\s+#.*$", "", raw).strip()
            cur[m.group(1)] = None if raw in ("null", "~", "") else raw
    return out


# ---------- skills ----------

def build_skill(name, manifest, src, agents):
    sk = manifest["skills"][name]
    registry = parse_registry(src.read("dependencies/registry.yaml"))
    for d in sk["dependencies"]:
        st = (registry.get(d["id"]) or {}).get("integrationStatus")
        if st not in ("approved", "integrated"):
            fail(f"skill {name}: dependency {d['id']} is {st or 'not registered'}, not approved or integrated")
    allow_all = {}
    for role in sk["roles"]:
        allow_all[role] = role_rules(agents, role)
    for step in sk["procedure"]:
        for span in CMD_SPAN_RE.findall(step):
            for role, (allow, deny) in allow_all.items():
                if not permitted(span, allow, deny):
                    fail(f"skill {name}: procedure command `{span}` is not allowed for {role}")
    ref_parts, sources = [], []
    for u in sk["reference_units"]:
        raw, level, _ = extract_unit(src, {**u, "headings": u.get("headings", [])} if "lines_containing" not in u else u)
        text = shift_headings(raw, 3 - level) if level else raw
        out = rewrite_links(text, u["source"], src, {}, {}, [])
        digest = sha256(raw)
        sources.append({"id": u["id"], "source": u["source"], "headings": u.get("headings"),
                        "blocks_starting_with": u.get("blocks_starting_with"), "lines_containing": u.get("lines_containing"),
                        "status": u["status"], "authority": u["authority"], "sha256": digest})
        ref_parts.append(marker({**u, "delivery": "skill_assigned"}, src.commit, digest, "+".join(sk["roles"]), sk["department"])
                         + "\n" + out.strip("\n"))
    ref_name = sk["reference_file"]
    mark = sk.get("retrieval_mark")
    mark_block = ""
    if mark:
        mark_block = ("\n\n## Retrieval mark\n\n`" + mark + "`\n\n"
                      "This line is only in this supporting file, so a pilot run can show the file was opened. It is not a rule.\n")
    ref_body = (f"# {sk['reference_title']}\n\n" + sk["reference_intro"] + "\n\n" + "\n\n".join(ref_parts) + mark_block + "\n")
    ref_doc = (f"<!-- GENERATED by {GENERATOR} v{GENERATOR_VERSION} for skill {name}. Do not edit by hand. "
               f"source-commit={src.commit} sha256={sha256(ref_body)} -->\n" + ref_body)
    rows = "\n".join(f"| {s['id']} | `{s['source']}` § {', '.join(s['headings'] or []) or 'lines'} | `{STATUSES[s['status']]}` "
                     f"| {s['authority']} | `{s['sha256'][:16]}` |" for s in sources)
    deps = "\n".join(f"- `{d['id']}`: {d['note']}" for d in sk["dependencies"])
    body = "\n".join([
        f"# {sk['title']}", "",
        f"Status: `{STATUSES[sk['status']]}`. Roles: {', '.join('`' + r + '`' for r in sk['roles'])}. "
        f"Department: {sk['department']}. Source commit `{src.commit}`.", "",
        "## Purpose", "", sk["purpose"], "",
        "## When to use it", "", *[f"- {a}" for a in sk["activation"]], "",
        "## Source knowledge", "",
        "| Unit | Source § section | Status | Authority | sha256 (first 16) |", "|---|---|---|---|---|", rows, "",
        f"Supporting file: [{ref_name}]({ref_name}). Open it before you choose seeds or decide what to keep in a "
        "refinement or a new pose.", "",
        "## Operating procedure", "", *[f"{i}. {s}" for i, s in enumerate(sk["procedure"], 1)], "",
        "## Approved dependencies", "", deps, "",
        "## Known limitations", "", *[f"- {x}" for x in sk["limitations"]], ""])
    fm = "\n".join(["---", f"name: {name}", f"description: {json.dumps(sk['description'], ensure_ascii=False)}", "---"])
    skill_doc = (fm + "\n" + f"<!-- GENERATED by {GENERATOR} v{GENERATOR_VERSION} for skill {name}. Do not edit by hand. "
                 f"source-commit={src.commit} sha256={sha256(body)} -->\n\n" + body)
    files = {posixpath.join(sk["dir"], "SKILL.md"): skill_doc, posixpath.join(sk["dir"], ref_name): ref_doc}
    revision = sha256("".join(f"{p}\n{files[p]}" for p in sorted(files)))
    return files, {"name": name, "dir": sk["dir"], "revision_sha256": revision, "sources": sources,
                   "files": {p: sha256(t) for p, t in sorted(files.items())}}


# ---------- secret scan (every generated file) ----------

SECRET_PATTERNS = [
    ("GitHub token", r"\bgh[pousr]_[A-Za-z0-9]{20,}"),
    ("GitHub fine-grained token", r"\bgithub_pat_[A-Za-z0-9_]{20,}"),
    ("Anthropic key", r"\bsk-ant-[A-Za-z0-9_-]{10,}"),
    ("API secret key", r"\bsk-[A-Za-z0-9]{32,}"),
    ("AWS access key", r"\bAKIA[0-9A-Z]{16}\b"),
    ("private key", r"-----BEGIN [A-Z ]*PRIVATE KEY-----"),
    ("bearer token", r"\bBearer\s+[A-Za-z0-9._~+/-]{20,}"),
    ("JWT", r"\beyJ[A-Za-z0-9_-]{8,}\.[A-Za-z0-9_-]{8,}\.[A-Za-z0-9_-]{8,}"),
    ("secret assignment", r"\b(?:GH_TOKEN|GITHUB_TOKEN|PAPERCLIP_API_KEY|ANTHROPIC_API_KEY|OPENAI_API_KEY)\s*[=:]\s*[\"']?[A-Za-z0-9_\-]{8,}"),
    ("Paperclip secret binding", r"\"secretId\"\s*:"),
    ("auth material file", r"\.credentials\.json|auth\.json\b|\bid_rsa\b"),
    ("machine-specific user path", r"\b[A-Za-z]:[\\/]+Users[\\/]+[^\\/\s]+|/home/[a-z][a-z0-9_-]*/"),
]


def secret_findings(text):
    """[(kind, match)] for credential values, secret configuration, auth material or machine-specific user paths."""
    out = []
    for kind, pat in SECRET_PATTERNS:
        out += [(kind, m.group(0)[:12] + "…") for m in re.finditer(pat, text)]
    return out


# ---------- generation ----------

def load_manifest(src, repo):
    if MANIFEST in src.paths:
        raw = git(repo, "show", f"{src.commit}:{MANIFEST}")
        origin = f"commit {src.commit}"
    else:
        raw = read_bytes(os.path.join(repo, MANIFEST))
        origin = "working tree (the manifest is not in the source commit yet)"
    return json.loads(raw.decode("utf-8")), sha256(raw.replace(b"\r\n", b"\n")), origin


def generate(src, manifest, manifest_sha, manifest_origin, roles=None):
    """{relative output path: text}. Every role and skill in the manifest unless `roles` limits it."""
    validate_manifest(manifest)
    agents = json.loads(src.read("config/paperclip/agents.json"))
    gen_sha = sha256(read_bytes(os.path.abspath(__file__)).replace(b"\r\n", b"\n"))
    out = {}
    skills = {}
    for name in sorted(manifest.get("skills", {})):
        files, info = build_skill(name, manifest, src, agents)
        out.update(files)
        skills[name] = info
    for role in sorted(roles or manifest["roles"]):
        if role not in manifest["roles"]:
            fail(f"role {role!r} is not in the manifest")
        doc, pkg = build_role(role, manifest, src, agents, manifest_sha, manifest_origin, gen_sha)
        pkg["skills"] = [{**s, "revision_sha256": skills.get(s["name"], {}).get("revision_sha256"),
                          "files": skills.get(s["name"], {}).get("files")} for s in pkg["skills"]]
        out[f"{OUT_DIR}/{role}/AGENTS.md"] = doc
        out[f"{OUT_DIR}/{role}/package.json"] = json.dumps(pkg, indent=2, ensure_ascii=False, sort_keys=True) + "\n"
    leaks = {p: f for p, t in out.items() for f in [secret_findings(t)] if f}
    if leaks:
        fail(f"secret scan: generated output would contain credential, secret or machine-specific material: {leaks}")
    return out


def parse_header(text):
    """(generator, version, role, source_commit, package_sha256, intact) of a generated package, or None."""
    text = text.replace("\r\n", "\n")
    m = HEADER_RE.match(text)
    if not m:
        return None
    return {"generator": m.group(1), "version": m.group(2), "role": m.group(3), "source_commit": m.group(4),
            "package_sha256": m.group(5),
            # a store may drop the final newline; anything else changes the hash
            "intact": m.group(5) in (sha256(text[m.end():]), sha256(text[m.end():].rstrip("\n") + "\n"))}


def freshness_findings(pkg, src):
    """Units whose source sections differ from `src`. Commit ids are not compared.

    A clean result means those sections match. It says nothing about files no unit names.
    """
    found = []
    for row in pkg.get("units") or []:
        want = row.get("section_sha256") or {}
        if not want:
            continue
        if not src.exists(row["source"]):
            found.append(f"{row['id']}: {row['source']} is not in the compared tree")
            continue
        body = split_frontmatter(src.read(row["source"]))[1]
        for heading, digest in want.items():
            text, _ = section(body, heading, row["source"])
            if sha256(text) != digest:
                found.append(f"{row['id']} § {heading}")
    return found


def committed_commit(repo, role):
    path = os.path.join(repo, OUT_DIR, role, "AGENTS.md")
    if os.path.isfile(path):
        h = parse_header(read_text(path))
        return h and h["source_commit"]
    return None


def main(argv=None):
    p = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    p.add_argument("--repo", default=REPO)
    p.add_argument("--commit", help="source commit (default: main; with --check, the commit the committed package records)")
    p.add_argument("--role", action="append", help="limit to these roles")
    p.add_argument("--check", action="store_true",
                   help="reproducibility at the pinned source commit; does not mean the knowledge is current")
    p.add_argument("--freshness", action="store_true",
                   help="compare the committed package's section hashes to --against (default HEAD)")
    p.add_argument("--against", help="revision for --freshness (default HEAD). Commit equality is not required.")
    a = p.parse_args(argv)
    sys.stdout.reconfigure(encoding="utf-8")
    sys.stderr.reconfigure(encoding="utf-8")
    try:
        manifest_roles = None
        commit = a.commit
        if not commit and a.check:
            commits = {committed_commit(a.repo, r) for r in json.loads(read_text(os.path.join(a.repo, MANIFEST)))["roles"]}
            commits.discard(None)
            if len(commits) > 1:
                fail(f"committed packages record different source commits: {sorted(commits)}")
            commit = commits.pop() if commits else "main"
        src = Source(a.repo, commit or "main")
        manifest, msha, origin = load_manifest(src, a.repo)
        files = generate(src, manifest, msha, origin, a.role or manifest_roles)
    except GenError as e:
        print(f"gen-role-packages: FAILED: {e}", file=sys.stderr)
        return 1
    if a.check:
        stale = []
        for rel, text in sorted(files.items()):
            path = os.path.join(a.repo, rel)
            cur = read_text(path, newline="") if os.path.isfile(path) else None
            if cur != text:
                stale.append(rel)
        for rel in stale:
            print(f"stale: {rel}")
        print(f"reproducible: {len(files) - len(stale)} of {len(files)} generated file(s) match at pinned source {src.commit[:12]}")
        print("A successful --check does not mean the knowledge is current. Freshness is --freshness.")
        return 1 if stale else 0
    if a.freshness:
        against = a.against or "HEAD"
        tree = Source(a.repo, against)
        worst = 0
        for role in sorted(a.role or manifest["roles"]):
            path = os.path.join(a.repo, OUT_DIR, role, "package.json")
            if not os.path.isfile(path):
                print(f"{role}: no committed package.json")
                worst = 1
                continue
            pkg = json.loads(read_text(path))
            found = freshness_findings(pkg, tree)
            pinned = pkg.get("source_commit", "")
            print(f"{role}: pinned source {pinned[:12]} compared by content to {tree.commit[:12]} "
                  f"(commit equality is not required)")
            if found:
                worst = 1
                for item in found:
                    print(f"  stale: {item}")
            else:
                print(f"  fresh: {len(pkg.get('units') or [])} unit section(s) match; unrelated files were not compared")
        return worst
    for rel, text in sorted(files.items()):
        path = os.path.join(a.repo, rel)
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
        print(f"wrote {rel} ({len(text.encode('utf-8'))} B)")
    for rel, text in sorted(files.items()):
        if rel.endswith("package.json"):
            pkg = json.loads(text)
            b, t = pkg["budget"], pkg["tokens_estimated"]
            print(f"{pkg['role']}: core {b['core_bytes']} B (max {b['core_max_bytes']}), command reference "
                  f"{b['command_reference_bytes']} B (max {b['command_reference_max_bytes']}), combined "
                  f"{b['combined_bytes']} B (max {b['combined_max_bytes']}); ESTIMATED tokens core "
                  f"{t['core']['low']}-{t['core']['high']}, command {t['command_reference']['low']}-"
                  f"{t['command_reference']['high']}, combined {t['combined']['low']}-{t['combined']['high']}; "
                  f"duplicates {len(pkg['duplicates'])} ({pkg['duplicate_bytes']} B)")
    return 0


