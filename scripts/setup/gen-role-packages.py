"""Generate role knowledge packages and Studio Skills from Company OS at one Git commit (ADR-024, PROPOSED).

Stdlib only. Writes local files only; never calls Paperclip. Run from the repository root:

    python -I scripts/setup/gen-role-packages.py                    # every role and skill in the manifest, at main
    python -I scripts/setup/gen-role-packages.py --commit <rev>     # another source commit
    python -I scripts/setup/gen-role-packages.py --check            # exit 1 if the committed output is stale

Inputs:
- Company OS sources (knowledge/, docs/, config/paperclip/agents.json) read with `git show <commit>:<path>`, never from
  the working tree, so the output is a pure function of (source commit, manifest, this script);
- config/paperclip/knowledge-manifest.json: read from the commit when it exists there, else from the working tree
  (its sha256 and origin are recorded either way).

Outputs (config/paperclip/generated/ and the skill folder named by the manifest):
- <role>/AGENTS.md: the managed entry file. Core instructions, then one command-reference block.
- <role>/package.json: provenance, per-unit hashes, byte budget, ESTIMATED tokens, coverage, duplicates, link rewrites.
- the skill's SKILL.md and reference files.

Validation (each one stops the run with evidence; nothing is dropped silently):
- missing source file, heading or selected block; a role-file block that no unit claims (source coverage);
- a relative link whose target or anchor does not exist at the commit (missing reference);
- a relative link survives into the output (unavailable channel; every link is rewritten to plain text);
- conflicting mandatory policies: one rule id with two texts, or `MUST X` and `MUST NOT X` (see find_conflicts);
- knowledge status: experimental or superseded content in an always-loaded or command-reference unit, or a unit
  declared `approved` whose first block carries a `PROPOSED`, `PLANNED` or `DEPRECATED` label;
- mandatory content leaving the verified channels: a normative sentence of an on-demand, skill or not-delivered unit
  that is neither in the delivered text nor covered by a manifest coverage entry; an exact allowed command form that
  is only in such a unit;
- budget: core > core_max_bytes, command reference > command_reference_max_bytes, or combined > combined_max_bytes.
"""
